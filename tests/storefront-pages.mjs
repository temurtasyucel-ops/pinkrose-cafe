import assert from 'node:assert/strict';
import {productSlug,productPath,findProduct,homeSelection,matchesFlavour,slugText} from '../lib/storefront-pages.ts';
const p={id:'cookie-9',name:'Gönülçelen',active:true,featured:true,ingredients:'Ceviz, beyaz çikolata. Elmalı tarçınlı dolgu.',description:'',flavourNotes:''};
assert.equal(productPath(p),'/kurabiyeler/gonulcelen');
assert.equal(productPath({...p,name:'Panelden değişen isim'}),productPath(p));
assert.equal(findProduct([p],'pamuk-prenses'),p);
assert.equal(findProduct([{...p,active:false}],'gonulcelen'),undefined);
assert.equal(findProduct([p],'olmayan-urun'),undefined);
const fresh={...p,id:'59275604-ab8f-4ef0-a5a9-c954fa333333',name:'Yeni Tat'};
assert.equal(findProduct([fresh],'onceki-isim-'+fresh.id),fresh);
assert.equal(productSlug(fresh),'yeni-tat-'+fresh.id);
assert.equal(slugText('ŞİRİNE & Fındık / İnci'), 'sirine-findik-inci');
const products=[{...p,id:'a',featured:false},{...p,id:'b',featured:true},{...p,id:'c',featured:true},{...p,id:'d',featured:true},{...p,id:'inactive',active:false}];
assert.deepEqual(homeSelection(products).map(p=>p.id),['b','c','d']);
assert.equal(homeSelection([]).length,0);
assert.equal(matchesFlavour(p,'fruit'),true);assert.equal(matchesFlavour(p,'nuts'),true);assert.equal(matchesFlavour(p,'chocolate'),false);
assert.equal(matchesFlavour({...p,ingredients:'Kakaolu hamur, bitter çikolata, vişne',flavourNotes:''},'chocolate'),true);
assert.equal(matchesFlavour({...p,ingredients:'Limonlu dolgu',allergens:'Fındık izleri içerebilir'},'nuts'),false);
console.log('PASS: stable product URLs, renamed and inactive products, alias lookup, three panel-selected home products and taste filters independent of allergen warnings.');
