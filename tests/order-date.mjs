import assert from 'node:assert/strict';
import {earliestOrderDate,validOrderDate,deliveryPreference,leadDays,validLeadDays} from '../lib/order-date.ts';
const now=new Date('2026-10-07T05:00:00Z');
assert.equal(earliestOrderDate(2,now),'2026-10-09');
assert.equal(earliestOrderDate(2,new Date('2026-10-07T21:10:00Z')),'2026-10-10');
assert.equal(earliestOrderDate(2,new Date('2026-12-30T21:00:00Z')),'2027-01-02');
assert.equal(earliestOrderDate(2,new Date('2028-02-27T12:00:00Z')),'2028-02-29');
assert.equal(leadDays({}),2);assert.equal(leadDays({leadDays:4}),4);
for(const v of [-1,31,2.5,'2',null,NaN])assert.equal(validLeadDays(v),false);
assert.equal(validLeadDays(0),true);
assert.equal(validOrderDate('2026-10-08','2026-10-09'),false);
assert.equal(validOrderDate('2026-02-30','2026-01-01'),false);
assert.equal(validOrderDate('2026-10-09','2026-10-09'),true);
assert.equal(deliveryPreference('2026-10-09','15:30',2,'tr',now),'9 Ekim 2026 · 15:30');
assert.equal(deliveryPreference('2026-10-09','',2,'en',now),'9 October 2026');
assert.equal(deliveryPreference('','',2,'tr',now),'');
assert.equal(deliveryPreference('','15:30',2,'tr',now),'15:30');
for(const d of ['2026-10-08','2026-02-30','Friday',null])assert.throws(()=>deliveryPreference(d,'',2,'tr',now));
for(const t of ['24:00','12:60','9:30','hello',null])assert.throws(()=>deliveryPreference('2026-10-09',t,2,'tr',now));
assert.throws(()=>deliveryPreference('2026-10-09','15:30',3,'tr',now));
console.log('PASS: Istanbul date boundaries, leap years, calendar validity, configurable lead time, optional preferences and TR/EN formatting.');
