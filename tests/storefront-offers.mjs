import assert from 'node:assert/strict';
import {basketOffer,seasonalProducts} from '../lib/pricing.ts';
const p={id:'cookie-1',active:true,stock:true,boxEligible:true,price:17000};
const c={products:[p,{...p,id:'cookie-2'},{...p,id:'extra',boxEligible:false}],bulkPricing:{minQty:2,unitPrice:15000}};
assert.equal(basketOffer(c,{}),null);
assert.deepEqual(basketOffer(c,{'cookie-1':1}),{remaining:1,savings:0,unitPrice:15000});
assert.deepEqual(basketOffer(c,{'cookie-1':1,'cookie-2':1}),{remaining:0,savings:4000,unitPrice:15000});
assert.deepEqual(basketOffer(c,{'cookie-1':1,extra:4}),{remaining:1,savings:0,unitPrice:15000});
assert.equal(basketOffer(c,{extra:2}),null);
assert.deepEqual(basketOffer({...c,bulkPricing:{minQty:3,unitPrice:16000}},{'cookie-1':2}),{remaining:1,savings:0,unitPrice:16000});
assert.equal(basketOffer({...c,bulkPricing:{minQty:2,unitPrice:18000}},{'cookie-1':2}),null);
const cheap={...p,id:'cheap',price:12000};
assert.equal(basketOffer({...c,products:[cheap]},{cheap:2}),null);
assert.deepEqual(basketOffer({...c,products:[p,cheap]},{'cookie-1':1,cheap:1}),{remaining:0,savings:2000,unitPrice:15000});
for(const override of [{active:false},{stock:false}])assert.equal(basketOffer({...c,products:[{...p,...override}]},{'cookie-1':2}),null);
assert.deepEqual(basketOffer({...c,bulkPricing:{minQty:1,unitPrice:15000}},{'cookie-1':1}),{remaining:0,savings:2000,unitPrice:15000});
assert.equal(seasonalProducts(c).length,0);
assert.deepEqual(seasonalProducts({...c,products:[{...p,seasonal:true},{...p,seasonal:true,stock:false},{...p,seasonal:true,active:false}]}),[{...p,seasonal:true}]);
console.log('PASS: quantity nudges follow mixed baskets, exclusions, cheaper items, availability and editable rules; seasonal announcements require active stocked selections.');
