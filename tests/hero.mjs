import assert from 'node:assert/strict';
import {heroSelection,heroSettings,heroImagePath} from '../lib/hero.ts';
const products=[1,3,5].map(n=>({id:'cookie-'+n,name:'Cookie '+n,image:'/products/cookie-'+n+'.webp',active:true}));
assert.deepEqual(heroSelection({},products).products.map(p=>p.id),['cookie-1','cookie-5','cookie-3']);
assert.equal(heroSelection({heroMode:'product',heroProductId:'cookie-5'},products).image,products[2].image);
assert.deepEqual(heroSelection({heroMode:'product',heroProductId:'cookie-5'},products.map(p=>({...p,active:p.id!=='cookie-5'}))).products.map(p=>p.id),['cookie-1','cookie-3']);
assert.equal(heroSelection({heroMode:'custom',heroImage:'https://bad.test/x.jpg'},products).mode,'collection');
assert.equal(heroImagePath('/api/images/abc-123'),true);assert.equal(heroImagePath('//bad.test/x.webp'),false);
assert.equal(heroSelection({},[]).products.length,0);
assert.equal(heroSettings({},products,{}).heroMode,'collection');
assert.deepEqual(heroSettings({},products,{heroMode:'product',heroProductId:'cookie-5'}).heroProductId,'cookie-5');
assert.throws(()=>heroSettings({heroMode:'collection',heroProductIds:['cookie-1','cookie-1']},products,{}),/farklı/);
assert.throws(()=>heroSettings({heroMode:'product',heroProductId:'missing'},products,{}),/ürün seçin/);
assert.throws(()=>heroSettings({heroMode:'custom',heroImage:'/api/images/abc-123'},products,{}),/açıklaması/);
assert.throws(()=>heroSettings({heroMode:'custom',heroImage:'https://bad.test/x.jpg',heroAlt:'Photo'},products,{}),/yükleme/);
const custom=heroSettings({heroMode:'custom',heroImage:'/api/images/abc-123',heroAlt:' Fotoğraf '},products,{});
assert.equal(custom.heroAlt,'Fotoğraf');assert.equal(heroSelection(custom,products).mode,'custom');
assert.deepEqual(heroSettings({},[],{}).heroProductIds,[]);
console.log('PASS: configurable hero modes, selected ordering, inactive-product fallback, empty catalog, custom image validation and legacy settings preservation.');
