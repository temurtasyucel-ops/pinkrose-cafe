import assert from 'node:assert/strict';
import {emptyCalendar,holdBooking,publicCalendar,orderBooking,availableDates,assertPreferredDate,cleanCalendarConfig} from '../lib/order-calendar.ts';
import {boxPriceRange} from '../lib/pricing.ts';
import {publicOrderStatus,trackingPath,trackingUrl} from '../lib/order-tracking.ts';
import {customerOrderMessage,paymentWhatsApp} from '../lib/types.ts';
const day='2026-10-19',later='2026-10-20',now=new Date('2026-10-17T10:00:00Z');
let s={...emptyCalendar,dailyLimit:4,closedDates:[later]};
s=holdBooking(s,'a',{orderId:'order-a',day,quantity:2});
// Retry and same-day status operations must not count twice.
s=holdBooking(s,'hold:a',{orderId:'order-a',day,quantity:2});
assert.equal(publicCalendar(s).booked[day],2);
s=holdBooking(s,'b',{orderId:'order-b',day,quantity:2});
assert.throws(()=>holdBooking(s,'c',{orderId:'order-c',day,quantity:1}));
assert.throws(()=>holdBooking(s,'a',{orderId:'order-a',day,quantity:1}));
assert.throws(()=>holdBooking(s,'c',{orderId:'order-c',day:later,quantity:1}));
assert.equal(availableDates({leadDays:2},publicCalendar(s),1,now)[0],'2026-10-21');
assert.throws(()=>assertPreferredDate(day,{leadDays:2},publicCalendar(s),1,now));
assert.throws(()=>assertPreferredDate('2026-10-18',{leadDays:2},undefined,1,now));
assert.throws(()=>assertPreferredDate('2028-01-01',{leadDays:2},undefined,1,now));
assert.equal(availableDates({leadDays:2},undefined,1,new Date('2026-10-17T21:01:00Z'))[0],later);
assert.throws(()=>cleanCalendarConfig({dailyLimit:-1,closedDates:[]}));
assert.throws(()=>cleanCalendarConfig({dailyLimit:10,closedDates:['2026-02-30']}));
assert.deepEqual(cleanCalendarConfig({dailyLimit:0,closedDates:[later,later]}),{dailyLimit:0,closedDates:[later]});
